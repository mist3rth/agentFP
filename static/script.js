document.addEventListener('DOMContentLoaded', () => {
    // Initialisation des icônes au chargement de la page
    lucide.createIcons();

    const form = document.getElementById('audit-form');
    const urlInput = document.getElementById('url-input');
    const submitBtn = document.getElementById('submit-btn');
    const loadingState = document.getElementById('loading-state');
    const errorState = document.getElementById('error-state');
    const resultContainer = document.getElementById('result-container');
    const reportContent = document.getElementById('report-content');
    const copyBtn = document.getElementById('copy-btn');
    const loadingSteps = document.querySelectorAll('.loading-steps span');

    form.addEventListener('submit', async (e) => {
        e.preventDefault();
        
        const url = urlInput.value.trim();
        if (!url) return;

        // Reset UI
        errorState.classList.add('hidden');
        resultContainer.classList.add('hidden');
        loadingState.classList.remove('hidden');
        submitBtn.disabled = true;
        
        // Auto-scroll pour bien voir le loader
        loadingState.scrollIntoView({ behavior: 'smooth', block: 'start' });
        
        // Reset steps
        loadingSteps.forEach(step => step.classList.remove('active'));
        loadingSteps[0].classList.add('active'); // Etape 1

        try {
            // Simulate step progression for UX because GenAI takes time
            setTimeout(() => {
                if(!resultContainer.classList.contains('hidden')) return;
                loadingSteps[0].classList.remove('active');
                loadingSteps[1].classList.add('active');
            }, 4000);

            setTimeout(() => {
                if(!resultContainer.classList.contains('hidden')) return;
                loadingSteps[1].classList.remove('active');
                loadingSteps[2].classList.add('active');
            }, 8000);

            const response = await fetch('/api/audit', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                },
                body: JSON.stringify({ url: url })
            });

            const data = await response.json();

            if (!response.ok) {
                throw new Error(data.error || 'Une erreur est survenue lors de l\'analyse.');
            }

            // Parse Markdown
            reportContent.innerHTML = marked.parse(data.report);
            
            // Recharger les icônes (si certaines sont dans le markdown ou l'UI révélée)
            lucide.createIcons();
            
            // Colorize specific tags generated by the prompt
            applyCustomStyles();

            // Show result
            loadingState.classList.add('hidden');
            resultContainer.classList.remove('hidden');
            
            // Auto-scroll pour voir le résultat complet
            resultContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });

        } catch (error) {
            console.error('Erreur:', error);
            errorState.innerHTML = `<i data-lucide="alert-circle" style="vertical-align: text-bottom; margin-right: 5px;"></i> ${error.message}`;
            errorState.classList.remove('hidden');
            loadingState.classList.add('hidden');
            lucide.createIcons(); // reload error icon
        } finally {
            submitBtn.disabled = false;
        }
    });

    copyBtn.addEventListener('click', async () => {
        try {
            await navigator.clipboard.writeText(reportContent.innerText);
            const originalHTML = copyBtn.innerHTML;
            copyBtn.innerHTML = '<i data-lucide="check"></i> Copié !';
            lucide.createIcons();
            setTimeout(() => {
                copyBtn.innerHTML = originalHTML;
                lucide.createIcons();
            }, 2000);
        } catch (err) {
            console.error('Failed to copy text: ', err);
        }
    });
});

function applyCustomStyles() {
    const content = document.getElementById('report-content');
    let html = content.innerHTML;
    
    // Remplacement du score global par une grosse carte colorée
    html = html.replace(/<h2[^>]*>Note Globale.*?(?:[:(])?\s*(\d{1,3})\s*\/\s*(100|10).*?<\/h2>/i, (match, scoreStr, maxScoreStr) => {
        let score = parseInt(scoreStr, 10);
        const maxScore = parseInt(maxScoreStr, 10);
        if (maxScore === 10) {
            score = score * 10;
        }
        
        let colorClass = 'score-green-big';
        let statusText = 'Excellent';
        let icon = 'shield-check';

        if (score < 50) {
            colorClass = 'score-red-big';
            statusText = 'Critique';
            icon = 'alert-octagon';
        } else if (score < 80) {
            colorClass = 'score-orange-big';
            statusText = 'À améliorer';
            icon = 'alert-triangle';
        }
        return `
        <div class="global-score-card ${colorClass}">
            <div class="score-header">
                <i data-lucide="${icon}"></i> Note Globale d'Audit
            </div>
            <div class="score-body">
                <div class="score-value">${score}<span>/100</span></div>
                <div class="score-status">${statusText}</div>
            </div>
        </div>`;
    });

    // Remplacement des autres H2 pour injecter des icônes
    html = html.replace(/<h2[^>]*>Fiche Technique Synthétique.*?<\/h2>/i, '<h2 class="section-icon"><i data-lucide="microscope"></i> Fiche Technique Synthétique</h2>');
    html = html.replace(/<h2[^>]*>1\. Résumé Exécutif.*?<\/h2>/i, '<h2 class="section-icon"><i data-lucide="file-text"></i> 1. Résumé Exécutif</h2>');
    html = html.replace(/<h2[^>]*>2\. Traçabilité.*?<\/h2>/i, '<h2 class="section-icon"><i data-lucide="search"></i> 2. Traçabilité & Labo</h2>');
    html = html.replace(/<h2[^>]*>3\. Dark Patterns.*?<\/h2>/i, '<h2 class="section-icon"><i data-lucide="eye-off"></i> 3. Dark Patterns & Biais</h2>');
    html = html.replace(/<h2[^>]*>4\. Tableau Constats.*?<\/h2>/i, '<h2 class="section-icon"><i data-lucide="table"></i> 4. Tableau Constats</h2>');
    html = html.replace(/<h2[^>]*>5\. Plan Action.*?<\/h2>/i, '<h2 class="section-icon"><i data-lucide="target"></i> 5. Plan Action</h2>');

    // Replace text tags with styled spans (inline scores)
    html = html.replace(/\[ROUGE\]/g, '<span class="score-red">DANGER</span>');
    html = html.replace(/\[ORANGE\]/g, '<span class="score-orange">ATTENTION</span>');
    html = html.replace(/\[VERT\]/g, '<span class="score-green">CONFORME</span>');
    html = html.replace(/🔴/g, '<span class="score-red">🔴</span>');
    html = html.replace(/🟠/g, '<span class="score-orange">🟠</span>');
    html = html.replace(/🟢/g, '<span class="score-green">🟢</span>');
    
    content.innerHTML = html;
}
